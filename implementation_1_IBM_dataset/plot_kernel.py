
import json

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

SURFACE = "#ffffff"
INK = "#0b0b0b"
INK_2 = "#52514e"
GRID = "#e3e2dd"
WALK = "#2a78d6"
ZMAP = "#eb6834"
ZZMAP = "#1baf7a"
CLASSICAL = "#8a8985"

plt.rcParams.update({
    "font.family": "sans-serif", "font.size": 8.5,
    "axes.edgecolor": GRID, "axes.labelcolor": INK_2,
    "xtick.color": INK_2, "ytick.color": INK_2,
    "figure.facecolor": SURFACE, "axes.facecolor": SURFACE,
    "savefig.facecolor": SURFACE,
})

rows = json.load(open("kernel_results.json"))
datasets = list(dict.fromkeys(r["dataset"] for r in rows))


def get(ds, method):
    for r in rows:
        if r["dataset"] == ds and r["method"] == method:
            return r
    return None


SERIES = [("walk kernel", WALK, "walk kernel"),
          ("Z kernel", ZMAP, "$Z$ kernel"),
          ("ZZ kernel", ZZMAP, "$ZZ$ kernel")]

fig, ax = plt.subplots(figsize=(7.4, 4.2))
y = np.arange(len(datasets))[::-1]
off = [0.27, 0.09, -0.09, -0.27]

ALL = SERIES + [("__classical__", CLASSICAL, "best classical kernel")]
for i, (key, col, lab) in enumerate(ALL):
    mus, sds = [], []
    for d in datasets:
        if key == "__classical__":
            v, m = max((get(d, k)["acc_mean"], k) for k in
                       ("classical RBF", "classical linear"))
            r = get(d, m)
        else:
            r = get(d, key)
        mus.append(r["acc_mean"]); sds.append(r["acc_std"])
    ypos = y + off[i]
    ax.errorbar(mus, ypos, xerr=sds, fmt="o", color=col, markersize=5.5,
                elinewidth=1.1, capsize=2.5, linewidth=0, label=lab,
                markeredgecolor=SURFACE, markeredgewidth=0.9, zorder=3)
    # label to the right of the error bar, not above the dot: at these
    # spacings an above-dot label collides with the neighbouring series
    for m, sd_, yp in zip(mus, sds, ypos):
        ax.text(m + sd_ + 0.7, yp, f"{m:.1f}", ha="left", va="center",
                fontsize=6.6, color=INK_2)

for yy in y:
    ax.axhline(yy, color=GRID, linewidth=0.6, zorder=0)

ax.set_yticks(y)
ax.set_yticklabels(datasets, fontsize=8.5)
ax.set_ylim(-0.65, len(datasets) - 0.35)
ax.set_xlabel("test accuracy (%),  mean $\\pm$ s.d. over 5 stratified splits")
ax.set_xlim(48, 108)
ax.grid(axis="x", color=GRID, linewidth=0.6, zorder=0)
ax.set_axisbelow(True)
for side in ("top", "right", "left"):
    ax.spines[side].set_visible(False)
ax.legend(loc="lower center", bbox_to_anchor=(0.5, 1.01), ncol=4,
          frameon=False, fontsize=7.6, handletextpad=0.3, columnspacing=1.6)

fig.tight_layout()
fig.savefig("fig_kernel_acc.pdf", bbox_inches="tight")
fig.savefig("fig_kernel_acc.png", dpi=200, bbox_inches="tight")
print("wrote fig_kernel_acc.pdf")

# ---------------------------------------------------------------- table --

ORDER = ["walk kernel", "Z kernel", "ZZ kernel",
         "classical RBF", "classical linear"]
NICE = {"walk kernel": "Walk kernel", "Z kernel": "$Z$ kernel",
        "ZZ kernel": "$ZZ$ kernel", "classical RBF": "Classical RBF",
        "classical linear": "Classical linear"}

with open("tab_kernel.tex", "w") as f:
    f.write("% Generated by plot_kernel.py -- do not edit by hand.\n")
    f.write("\\begin{table}[htbp]\n\\centering\\small\n")
    f.write("\\caption{Quantum kernel results. Test accuracy is the mean and "
            "standard deviation over five stratified splits; $\\bar{K}$ is the "
            "mean off-diagonal entry of the training Gram matrix, a direct "
            "measure of kernel concentration. Best quantum kernel per dataset "
            "in bold.}\n\\label{tab:kernel}\n")
    f.write("\\begin{tabular}{llrrr}\n\\hline\n")
    f.write("Dataset & Method & Qubits & Test acc.\\ (\\%) & $\\bar{K}$ \\\\\n")
    f.write("\\hline\n")
    for d in datasets:
        qbest = max(get(d, m)["acc_mean"] for m in ORDER[:3])
        for m in ORDER:
            r = get(d, m)
            q = r["qubits"] if r["family"] == "quantum" else "---"
            kb = (f"{r['offdiag']:.3f}" if r["family"] == "quantum" else "---")
            # \textbf does not bold math, so bold inside the math mode
            if r["family"] == "quantum" and abs(r["acc_mean"] - qbest) < 1e-9:
                acc = (f"$\\mathbf{{{r['acc_mean']:.1f} \\pm "
                       f"{r['acc_std']:.1f}}}$")
            else:
                acc = f"${r['acc_mean']:.1f} \\pm {r['acc_std']:.1f}$"
            f.write(f"{d if m == ORDER[0] else ''} & {NICE[m]} & {q} & "
                    f"{acc} & {kb} \\\\\n")
        f.write("\\hline\n")
    f.write("\\end{tabular}\n\\end{table}\n")
print("wrote tab_kernel.tex")
